"""Replace the results-tables section of docs/FINAL_REPORT.md with results/tables/tables.md, unedited.

Run after `python -m app.evaluation.report`.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPORT = ROOT / "docs" / "FINAL_REPORT.md"
TABLES = ROOT / "results" / "tables" / "tables.md"
HEADING = "## Results tables"
INTRO = ("Generated by `python -m app.evaluation.report` from `results.csv`; pasted unedited. "
         "Rows named `errors_*` are the retry runs (heading 6).")


def main() -> None:
    text = REPORT.read_text(encoding="utf-8")
    if HEADING not in text:
        raise SystemExit(f"{REPORT} has no '{HEADING}' heading")
    body = text[: text.index(HEADING)]
    tables = TABLES.read_text(encoding="utf-8").strip()
    REPORT.write_text(f"{body}{HEADING}\n\n{INTRO}\n\n{tables}\n", encoding="utf-8")
    print(f"pasted {TABLES.relative_to(ROOT)} into {REPORT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
